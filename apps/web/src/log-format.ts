// 화면 전보 = 인게임 전보 문구만 (FIX-033, 사용자 지정 2026-10-13).
// 엔진 로그 원본(감사·역재현·MCP·시험이 읽음)은 그대로 두고, 화면에 그릴 때만 검증용 줄을 숨기고 검증용 꼬리를 뗀다.
//   null = 숨김(검증·참고용 줄), 문자열 = 그 문자열로 표시(턴 접두 "N턴: " 은 남긴 채)

/** 인게임 전보에 없는 검증·참고용 줄 */
const HIDE: RegExp[] = [
  /└\s*\[상태\]/, /└\[계산\]/,                     // 행동 시작 무장 스냅숏
  /^\d+턴:\s+\[상태이상\]/, /^\d+턴:\s+\[스택\]/,     // 상태·스택 현황
  /^\d+턴:\s+(무력|지력)[ :]/,                        // 스냅숏 능력치 줄
  /^\d+턴:\s{4,}[가-힣]/,                           // 깊게 들여쓴 증감 요약 "    주는피해 6.00% · 받는피해 …"
  /^\d+턴:\s+\[[^\]]+\] 무 [\d.]+ 지 [\d.]+ 통/,      // 포진 무장 요약
  /^\d+턴:\s+└ \[[^\]]+\] \((지휘|패시브|액티브|추격)\) 대기/,   // 전법 대기 표시
  /^\d+턴:\s+※/,                                    // 엔진·범위 안내 (화면 위 안내문으로 대신)
  /^\d+턴:\s+\[(아군|적군)\] 진영 /,                  // 진영·배치 요약
  /^\d+턴:\s+\[[^\]]+\]이\(가\) 「[^」]+」 상태를 획득했습니다/,   // 바로 앞 "효과가 발동됐습니다"의 반복
];

/** 줄 끝 검증용 꼬리 */
const TAILS: Array<[RegExp, string]> = [
  [/ \(치유율 [\d.]+%, 시전자 지력 [\d.]+\)/, ''],                       // 회복 계산값 — 감사 내부 전용
  [/ \(\d+턴 지속\)( — .+의 【[^】]+】)?$/, ''],                           // 상태 지속·출처
  [/효과가 발동됐습니다\.$/, '효과가 발동했습니다.'],                        // 인게임 문구
  [/(발동했습니다\.) \((턴 시작|턴 종료)\)$/, '$1'],
  [/(효과를 발동합니다\.) \(.+?의 \[[^\]]+\](으)?로 지시됨\)$/, '$1'],
  [/ \(.+?의 (무력|지력) [\d.]+ 기준 고정 피해\)$/, ''],
  [/(장착) \(근사\)/, '$1'],                                            // 근사 표시는 결과 패널(근사 효과 목록)에서
];

export function gameLine(l: string): string | null {
  if (HIDE.some(r => r.test(l))) return null;
  let t = l;
  for (const [r, s] of TAILS) t = t.replace(r, s);
  return t;
}
